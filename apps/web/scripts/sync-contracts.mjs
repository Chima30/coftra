// Generates src/lib/contracts/generated.ts from Foundry artifacts and deployment records.
// Run after `forge build` and after each deployment step:  pnpm sync:contracts
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, "..", "..", "..", "contracts");
const outFile = join(here, "..", "src", "lib", "contracts", "generated.ts");

const artifacts = {
  vaultAbi: "CoftraVault.sol/CoftraVault.json",
  reactiveAbi: "CoftraReactive.sol/CoftraReactive.json",
  registryAbi: "CoftraMilestoneVerifier.sol/CoftraMilestoneVerifier.json",
  mockUsdcAbi: "CoftraMockUSDC.sol/CoftraMockUSDC.json",
  demoNftAbi: "CoftraDemoNFT.sol/CoftraDemoNFT.json",
};

let src = "// AUTO-GENERATED by scripts/sync-contracts.mjs. Do not edit by hand.\n\n";
for (const [name, path] of Object.entries(artifacts)) {
  const json = JSON.parse(readFileSync(join(contracts, "out", path), "utf8"));
  src += `export const ${name} = ${JSON.stringify(json.abi, null, 2)} as const;\n\n`;
}

const depPath = join(contracts, "deployments", "base-sepolia.json");
const deployment = existsSync(depPath) ? JSON.parse(readFileSync(depPath, "utf8")) : null;
src += `/** Addresses from contracts/deployments/base-sepolia.json. null = not deployed yet. */\n`;
src += `export const deployment = ${JSON.stringify(deployment, null, 2)} as DeploymentRecord | null;\n\n`;
src += `export type DeploymentRecord = {
  token: \`0x\${string}\`;
  demoNft: \`0x\${string}\`;
  verifierRegistry: \`0x\${string}\`;
  reactive?: \`0x\${string}\`;
  vault?: \`0x\${string}\`;
  callbackProxy?: \`0x\${string}\`;
  originChainId: number;
  assetsBlock?: number;
  reactiveBlock?: number;
  vaultBlock?: number;
};\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, src);
console.log(`wrote ${outFile} (deployment: ${deployment ? "present" : "none"})`);
